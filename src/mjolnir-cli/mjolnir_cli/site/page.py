def emit_site(layout: RepoLayout, out_dir: Path, data: dict | None = None) -> Path:
    """Write the v2 tree into ``out_dir``; return the shell path.

    ``data`` (a preloaded ``load_verify`` result) is accepted for call
    compatibility with the v1 single-page builder and unused: payloads are
    built per measured pair from the raw documents."""
    from mjolnir_cli.site.data import build_site

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    m, files = build_site(layout)
    for name in ("app.js", "app.css"):
        shutil.copyfile(_ASSETS / name, out_dir / name)
    (out_dir / "manifest.json").write_text(json.dumps(m, indent=1, sort_keys=True) + "\n")
    for rel, body in files:
        p = out_dir / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body)
    p = out_dir / "index.html"
    p.write_text(_SHELL.replace("__PLOTLY__", PLOTLY))
    print(f"[mjolnir] interactive site -> {p} ({len(files)} pair payloads)")
    return p
